_LANG_INDEX = {"hi": 0, "mr": 1}


def localize_signal(signal: dict, lang: str) -> dict:
    """A copy of a signal dict with its label and why in `lang`; English (or an unknown id) is returned as is.

    `params` is consumed here and removed, so it never reaches the API response. `evidence` is left untouched."""
    out = dict(signal)
    params = out.pop("params", None) or {}
    texts = SIGNALS.get(signal.get("id", ""))
    if lang in _LANG_INDEX and texts:
        i = _LANG_INDEX[lang]
        out["label"] = texts["label"][i].format(**params)
        out["why"] = texts["why"][i].format(**params)
    return out
